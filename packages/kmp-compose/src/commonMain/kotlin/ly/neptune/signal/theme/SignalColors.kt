        surfaceCard = Color(0xFF05080A),
        surfaceSoft = Color(0xFF080F13),
        textInverse = contentColorFor(primary),
    )

    private fun contentColorFor(color: Color): Color {
        val luma = (0.299f * color.red) + (0.587f * color.green) + (0.114f * color.blue)
        return if (luma > 0.62f) Color(0xFF071C2E) else Color.White
    }
