    fun whiteLabel(
        primary: Color,
        secondary: Color = Color(0xFF00A8AE),
        accent: Color = Color(0xFFEB4E4D),
        ink: Color = Color(0xFF071C2E),
        surface: Color = Color(0xFFFAFCFC),
        primaryContainer: Color = Color(0xFFE8F1FF),
        secondaryContainer: Color = Color(0xFFD8F6F7),
        tertiaryContainer: Color = Color(0xFFFFE5E4),
        dark: Boolean = false,
        black: Boolean = false,
    ): SignalColors = when {
        black -> whiteLabelBlack(primary = primary, secondary = secondary, accent = accent)
        dark -> whiteLabelDark(primary = primary, secondary = secondary, accent = accent)
        else -> SignalColors(
            primary = primary,
            onPrimary = contentColorFor(primary),
            primaryContainer = primaryContainer,
            onPrimaryContainer = ink,
            secondary = secondary,
            onSecondary = contentColorFor(secondary),
            secondaryContainer = secondaryContainer,
            onSecondaryContainer = ink,
            tertiary = accent,
            onTertiary = contentColorFor(accent),
            tertiaryContainer = tertiaryContainer,
            onTertiaryContainer = ink,
            surface = surface,
            onSurface = ink,
            bankPrimary = primary,
            bankSecondary = secondary,
            bankAccent = accent,
            surfacePaper = surface,
            textPrimary = ink,
            textInverse = contentColorFor(primary),
        )
    }

